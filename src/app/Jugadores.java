    private void btnSelectTodosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSelectTodosActionPerformed
        // TODO add your handling code here:

    // Comprobar si todos los jugadores están seleccionados
    boolean todosSeleccionados =
            txtPato.isSelected() &&
            txtDiego.isSelected() &&
            txtBastian.isSelected() &&
            txtAlexis.isSelected() &&
            txtJohann.isSelected();

            // Cambiar el estado de todos los jugadores
            txtPato.setSelected(!todosSeleccionados);
            txtDiego.setSelected(!todosSeleccionados);
            txtBastian.setSelected(!todosSeleccionados);
            txtAlexis.setSelected(!todosSeleccionados);
            txtJohann.setSelected(!todosSeleccionados);

            // Actualizar el texto del botón
            if (todosSeleccionados) {
                btnSelectTodos.setText("Seleccionar todos");
            } else {
                btnSelectTodos.setText("Borrar");
            }
    }//GEN-LAST:event_btnSelectTodosActionPerformed

    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        // TODO add your handling code here:
        jugadores.clear();

        if (txtPato.isSelected()) {
            jugadores.add(txtPato.getText());
        }
        if (txtDiego.isSelected()) {
            jugadores.add(txtDiego.getText());
        }
        if (txtBastian.isSelected()) {
            jugadores.add(txtBastian.getText());
        }
        if (txtAlexis.isSelected()) {
            jugadores.add(txtAlexis.getText());
        }
        if (txtJohann.isSelected()) {
            jugadores.add(txtJohann.getText());
        }
        if (jugadores.size() < 3) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Debes seleccionar al menos 3 jugadores."
            );
            return;
        }

        // Reiniciar el contador de rondas
        Principal.numeroRonda = 0;
        Principal.ultimoResultado = "";

        // Limpiar puntajes y estadísticas anteriores
        Principal.puntajes.clear();
        Principal.rondasGanadas.clear();
        Principal.winRateAcumulado.clear();
        Principal.partidasJugadas.clear();

        // Inicializar los datos de cada jugador
        for (int i = 0; i < jugadores.size(); i++) {

            Principal.puntajes.add(0);
            Principal.rondasGanadas.add(0);
            Principal.winRateAcumulado.add(0.0);
            Principal.partidasJugadas.add(0);
        }

        Principal ventana = new Principal();
        ventana.setLocationRelativeTo(null);
        ventana.setVisible(true);

        this.dispose();
    }//GEN-LAST:event_btnAceptarActionPerformed

